/// One row of an on-chain registration: the unit an account grows by when
/// the runtime's 10,240-byte step cannot hold the whole key.
#[svm_test]
fn prepare_row_into_heap() {
    const HEAP: *mut u8 = 0x3_0000_0000 as *mut u8;
    // SAFETY: as in `prepare_into_heap`; one row fits.
    let bytes =
        unsafe { core::slice::from_raw_parts_mut(HEAP, PreparedVerifyingKey::ROW_BYTE_LEN) };
    let row = PreparedVerifyingKey::borrow_row_mut(bytes).unwrap();
    black_box(&VerifyingKey::from_bytes(&PUBLIC_KEY))
        .prepare_row_into(black_box(1), row)
        .unwrap();
    black_box(row);
}
