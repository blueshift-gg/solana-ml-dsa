/// Prepared at compile time; lives in rodata, never on the stack.
static KEY: PreparedVerifyingKey = {
    let mut key = PreparedVerifyingKey::ZERO;
    VerifyingKey::from_bytes(&PUBLIC_KEY).prepare_into(&mut key);
    key
};

#[svm_test]
fn verify_prepared() {
    let out = black_box(&KEY).verify_with_context(
        black_box(&MESSAGE),
        black_box(&CONTEXT),
        Signature::ref_from_bytes(black_box(&SIGNATURE)).unwrap(),
    );
    assert!(out.is_ok());
    let _ = black_box(out);
}

/// Rejection at the final commitment check costs the whole verification.
#[svm_test(error = ProgramError::Custom(1))]
fn reject_tampered_message() -> u64 {
    let mut message = MESSAGE;
    message[0] ^= 1;
    let out = black_box(&KEY).verify_with_context(
        black_box(&message),
        black_box(&CONTEXT),
        Signature::ref_from_bytes(black_box(&SIGNATURE)).unwrap(),
    );
    black_box(out).is_err() as u64
}

/// Rejection at the norm check happens before any hashing.
#[svm_test(error = ProgramError::Custom(1))]
fn reject_out_of_norm_z() -> u64 {
    let mut signature = SIGNATURE;
    // First z coefficient's 18-bit field set to 0 → coefficient γ1 ≥ γ1 − β.
    signature[32] = 0;
    signature[33] = 0;
    signature[34] &= 0xFC;
    let out = black_box(&KEY).verify_with_context(
        black_box(&MESSAGE),
        black_box(&CONTEXT),
        Signature::ref_from_bytes(black_box(&signature)).unwrap(),
    );
    black_box(out).is_err() as u64
}

/// On-chain registration: the key prepared into the program's heap region,
/// which stands in for the account.
#[svm_test]
fn prepare_into_heap() {
    const HEAP: *mut u8 = 0x3_0000_0000 as *mut u8;
    // SAFETY: the SBPF heap region is 32 KB of writable, 8-byte aligned
    // memory owned by this invocation; `PreparedVerifyingKey::BYTE_LEN` fits.
    let bytes = unsafe { core::slice::from_raw_parts_mut(HEAP, PreparedVerifyingKey::BYTE_LEN) };
    let key = PreparedVerifyingKey::mut_from_bytes(bytes).unwrap();
    black_box(&VerifyingKey::from_bytes(&PUBLIC_KEY)).prepare_into(key);
    black_box(key.public_key_hash());
}

