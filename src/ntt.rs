/// `b · Q^-1 mod 2^64` with `b ≡ −ZETAS[k] · 2^32 (mod Q)` centred, so
/// that `plantard(a, PLANTARD[k]) ≡ ZETAS[k] · a · 2^-32`, the reference's
/// Montgomery twiddle product.
pub const PLANTARD: [u64; N] = {
    let mut table = [0u64; N];
    let mut k = 0;
    while k < N {
        // The reference twiddle product is ZETAS[k] · a · 2^-32.
        table[k] = plantard_constant(mul_mod(ZETAS[k], MONT_INV));
        k += 1;
    }
    table
};

/// `2^-32 mod Q`, as a standard representative.
const MONT_INV: i64 = {
    // 2^32 · x ≡ 1: x = (2^32)^(Q−2) by Fermat, computed by squaring.
    let mut base = mul_mod(1 << 32, 1);
    let mut exp = Q - 2;
    let mut acc = 1;
    while exp > 0 {
        if exp & 1 == 1 {
            acc = mul_mod(acc, base);
        }
        base = mul_mod(base, base);
        exp >>= 1;
    }
    acc
};

/// `a[j], a[j + len] ← a[j] + t, a[j] − t` with `t ≡ ζ · a[j + len]`.
#[inline(always)]
const fn ct(a: &mut [i64; N], j: usize, len: usize, zeta: u64) {
    let t = plantard(a[j + len], zeta);
    a[j + len] = a[j] - t;
    a[j] += t;
}

/// `a[j], a[j + len] ← a[j] + a[j + len], t` with `t ≡ ζ · (a[j] − a[j + len])`.
#[inline(always)]
const fn gs(a: &mut [i64; N], j: usize, len: usize, zeta: u64) {
    let t = a[j];
    let u = a[j + len];
    a[j] = t + u;
    a[j + len] = plantard(t - u, zeta);
}

