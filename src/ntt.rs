//! Number-theoretic transform over `Z_Q[x]/(x^256 + 1)`, FIPS 204
//! Algorithms 41 and 42 as PQClean `ntt.c` schedules them: forward to
//! bit-reversed order without reductions after additions, inverse without
//! its final scaling pass (the prepared tables carry that factor).
//!
//! Three departures from the reference loop, each pinned in `tests.rs`:
//! the 1024 butterflies of each direction are written out, so every index
//! and twiddle is a constant (a loop costs a third of a butterfly on SBPF);
//! they are ordered in merged layer pairs, each group of four coefficients
//! crossing two layers while in registers (groups are disjoint and read only
//! their own outputs, so no value changes); and the twiddle product is
//! Plantard's, with [`PLANTARD`] derived from [`ZETAS`] so that every
//! coefficient is congruent to the reference's, in half the range.
//!
//! Plantard admits inputs up to `Q · 2^8`. Forward inputs are below `2^17`
//! and grow by under `Q/2` per layer; inverse inputs are below `Q` and at
//! most double per layer over the seven layers before the last multiply.

